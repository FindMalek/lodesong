// Regenerates apps/player/src/lib/look-preset-table.ts from ui.shadcn.com (the same /init resolution `shadcn init --preset` uses).
// Run it by hand when the `shadcn` dev dependency is bumped: bun scripts/gen-preset-table.ts. The app never fetches at runtime.
const BASES = ["neutral", "stone", "zinc", "gray", "mauve", "olive", "mist", "taupe"];
const THEMES = [
  ...BASES,
  "amber",
  "blue",
  "cyan",
  "emerald",
  "fuchsia",
  "green",
  "indigo",
  "lime",
  "orange",
  "pink",
  "purple",
  "red",
  "rose",
  "sky",
  "teal",
  "violet",
  "yellow",
];
const THEME_KEYS = ["primary", "primary-foreground", "sidebar-primary", "sidebar-primary-foreground"];
const KEYS = [
  "background",
  "foreground",
  "card",
  "card-foreground",
  "popover",
  "popover-foreground",
  "secondary",
  "secondary-foreground",
  "muted",
  "muted-foreground",
  "accent",
  "accent-foreground",
  "border",
  "input",
  "ring",
  "sidebar",
  "sidebar-foreground",
  "sidebar-accent",
  "sidebar-accent-foreground",
  "sidebar-border",
  "sidebar-ring",
];
type Vars = Record<string, string>;
type Schemes = { light: Vars; dark: Vars };

async function resolve(baseColor: string, theme: string): Promise<Schemes> {
  const query = new URLSearchParams({
    base: "radix",
    style: "nova",
    baseColor,
    theme,
    iconLibrary: "lucide",
    font: "geist",
    rtl: "false",
    menuAccent: "subtle",
    menuColor: "default",
    radius: "default",
  });
  const response = await fetch(`https://ui.shadcn.com/init?${query}`);
  if (!response.ok) throw new Error(`${baseColor}/${theme}: ${response.status}`);
  return ((await response.json()) as { cssVars: Schemes }).cssVars;
}

const pick = (vars: Vars, keys: string[]): string[] => keys.map((key) => vars[key] ?? "");

const bases: Record<string, [string[], string[]]> = {};
for (const base of BASES) {
  const own = await resolve(base, base).catch(() => null);
  if (!own) continue;
  bases[base] = [pick(own.light, KEYS), pick(own.dark, KEYS)];
}
const themes: Record<string, [string[], string[]]> = {};
for (const theme of THEMES) {
  // The neutral-family themes only pair with their own base color; the accent ones pair with any.
  const neutral = BASES.includes(theme);
  const own = await resolve(neutral ? theme : "zinc", theme).catch(() => null);
  if (!own) continue;
  themes[theme] = [pick(own.light, THEME_KEYS), pick(own.dark, THEME_KEYS)];
  if (neutral) continue;
  const other = await resolve("olive", theme);
  for (const mode of ["light", "dark"] as const) {
    for (const key of Object.keys(own[mode])) {
      const sameAccent = THEME_KEYS.includes(key) ? own[mode][key] === other[mode][key] : true;
      if (!sameAccent) throw new Error(`${theme}: ${key} depends on the base color`);
    }
  }
}

const out = `// Generated by scripts/gen-preset-table.ts from ui.shadcn.com (shadcn ${(await Bun.file("node_modules/shadcn/package.json").json()).version}). Do not edit.
// Loaded lazily, only when a shadcn preset code is imported. Exempt from the raw-color check (scripts/check-colors.ts): it is data.
export const BASE_KEYS = ${JSON.stringify(KEYS)} as const;
export const THEME_KEYS = ${JSON.stringify(THEME_KEYS)} as const;
export const BASES: Record<string, [string[], string[]]> = ${JSON.stringify(bases)};
export const THEMES: Record<string, [string[], string[]]> = ${JSON.stringify(themes)};
`;
await Bun.write("apps/player/src/lib/look-preset-table.ts", out);
console.log(`wrote look-preset-table.ts: ${Object.keys(bases).length} base colors, ${Object.keys(themes).length} themes`);
